// One-off: bake a land/sea bitmask for the /world globe.
//   node scripts/bake-land.mjs
// Reads Natural Earth 50m land (world-atlas), scanline-fills every polygon
// onto an equirectangular grid, and writes the mask as base64 bits to
// app/world/land.ts. The globe samples it at runtime, so the browser
// needs no network and no geo library.
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-50m.json");
const land = feature(topo, topo.objects.land);

const W = 720;
const H = 360;
const cells = new Uint8Array(W * H);
const polys = [];
for (const f of land.features ?? [land]) {
  const g = f.geometry;
  if (g.type === "Polygon") polys.push(g.coordinates);
  else if (g.type === "MultiPolygon") polys.push(...g.coordinates);
}
// Even-odd fill: each row's centre latitude is crossed with every ring edge
// of a polygon (holes included), and cells between pairs of crossings are land.
for (const rings of polys) {
  for (let y = 0; y < H; y++) {
    const lat = 90 - ((y + 0.5) / H) * 180;
    const xs = [];
    for (const ring of rings) {
      for (let i = 0; i < ring.length - 1; i++) {
        const [x0, y0] = ring[i];
        const [x1, y1] = ring[i + 1];
        if (y0 > lat !== y1 > lat) xs.push(x0 + ((lat - y0) / (y1 - y0)) * (x1 - x0));
      }
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const from = Math.ceil(((xs[k] + 180) / 360) * W - 0.5);
      const to = Math.floor(((xs[k + 1] + 180) / 360) * W - 0.5);
      for (let x = Math.max(0, from); x <= Math.min(W - 1, to); x++) cells[y * W + x] = 1;
    }
  }
}
const bits = new Uint8Array((W * H) / 8);
let n = 0;
cells.forEach((c, i) => {
  if (c) {
    bits[i >> 3] |= 1 << (i & 7);
    n++;
  }
});
const out = `// Generated by scripts/bake-land.mjs from Natural Earth 50m land (world-atlas).
// ${W}x${H} equirectangular grid, one bit per cell, row 0 = 90°N, column 0 = 180°W.
export const LAND = { w: ${W}, h: ${H}, bits: "${Buffer.from(bits).toString("base64")}" };
`;
fs.writeFileSync(new URL("../app/world/land.ts", import.meta.url), out);
console.log(`land cells: ${n} of ${W * H} (${((n / (W * H)) * 100).toFixed(1)}%); ${out.length} bytes`);
// quick look: a coarse ASCII map
for (let y = 0; y < H; y += 12) {
  let row = "";
  for (let x = 0; x < W; x += 6) row += cells[y * W + x] ? "#" : ".";
  console.log(row);
}
